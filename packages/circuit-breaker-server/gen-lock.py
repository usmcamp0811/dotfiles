#!/usr/bin/env python3
"""Regenerate requirements.lock.txt from upstream's poetry.lock.

    nix shell nixpkgs#python3 -c python gen-lock.py <upstream-src-dir> > requirements.lock.txt

For every package the application installs (apps/backend/requirements*.txt) it emits
the pinned version plus the sha256 of *every* file poetry.lock lists for it, so pip can
verify whatever wheel it picks. Packages that cannot be fetched as a wheel from PyPI are
reported on stderr and skipped (the Nix package supplies them another way or documents
why they are absent):

  * environment-marker packages for other platforms (pywin32),
  * python-nmap (sdist only; upstream ships a local wheel),
  * certbot and its plugins (the optional ACME extra is not in poetry.lock).
"""
import re
import sys
import tomllib
from pathlib import Path

src = Path(sys.argv[1])
backend = src / "apps" / "backend"
lock = tomllib.loads((backend / "poetry.lock").read_text())
packages = {p["name"].lower().replace("_", "-"): p for p in lock["package"]}

wanted = {}
for name in ("requirements.txt", "requirements-pg.txt"):
    for line in (backend / name).read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "==" not in line:
            continue
        spec, _, marker = line.partition(";")
        pkg, _, ver = spec.partition("==")
        wanted[pkg.strip().lower().replace("_", "-")] = (ver.strip(), marker.strip())

skipped = []
out = []
for pkg, (ver, marker) in sorted(wanted.items()):
    if "Windows" in marker:
        skipped.append((pkg, "windows only"))
        continue
    entry = packages.get(pkg)
    if entry is None:
        skipped.append((pkg, "not in poetry.lock"))
        continue
    if entry["version"] != ver:
        sys.exit(f"{pkg}: requirements pin {ver} but poetry.lock has {entry['version']}")
    wheels = [f for f in entry["files"] if f["file"].endswith(".whl")]
    if not wheels:
        skipped.append((pkg, "no wheel on PyPI"))
        continue
    hashes = " ".join(f"--hash={f['hash']}" for f in entry["files"])
    out.append(f"{entry['name']}=={ver} {hashes}")

print("# Generated by gen-lock.py from upstream poetry.lock - do not edit.")
print("\n".join(out))
for pkg, why in skipped:
    print(f"skipped {pkg}: {why}", file=sys.stderr)
